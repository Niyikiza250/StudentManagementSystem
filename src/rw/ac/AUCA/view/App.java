    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        // TODO add your handling code here:
        // step 1: by making field required
        if (txtTin.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "TIN is required!","VALIDATION",JOptionPane.WARNING_MESSAGE);
            
        }else if (txtNames.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Names is required!","VALIDATION",JOptionPane.WARNING_MESSAGE);
            
        }
        
        else if (txtAmount.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Amount is required!","VALIDATION",JOptionPane.WARNING_MESSAGE);
            
        }
        else{
            if (txtTin.getText().length()!=9) {
            JOptionPane.showMessageDialog(this, "TIN is required!","VALIDATION",JOptionPane.WARNING_MESSAGE);
            
        }else{
        JOptionPane.showMessageDialog(this, "Data saved Successfully!");
        }
        }
    }//GEN-LAST:event_btnRegisterActionPerformed
    
