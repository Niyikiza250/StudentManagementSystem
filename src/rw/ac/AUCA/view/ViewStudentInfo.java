    private void clearFields() {
    txtstudentId.setText("");
    txtFullName.setText("");
    txtEmail.setText("");
    txtAge.setText("");
    txtGender.setText("");
    txtFaculty.setText("");
    txtDepartment.setText("");
    txtstudentId.requestFocus();
}
    private  void loadTable(){
        try {
            StudentDao dao = new StudentDao();
            List<StudentInfo> students = dao.getAllStudents();
            DefaultTableModel model = (DefaultTableModel)tblStudent.getModel();
            model.setRowCount(0);
            for (StudentInfo st : students) {
                model.addRow(new Object[]{
                    st.getStudent_Id(),
                    st.getStudent_name(),
                    st.getEmail(),
                    st.getAge(),
                    st.getGender(),
                    st.getFaculty(),
                    st.getDepatment()
                
            });
                
            }
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,"Database Error"+ e.getMessage());
        }
    }
    
    private void filTable(){
        try {
            String IdToSearch=txtSearch.getText();
            
            StudentInfo studeToFill= new StudentInfo();
            studeToFill.setStudent_Id(IdToSearch);
            StudentDao searchDao = new StudentDao();
            StudentInfo studSearch = searchDao.searchStudent(studeToFill);
           txtstudentId.setText(studSearch.getStudent_Id());
           txtFullName.setText(studSearch.getStudent_name());
           txtEmail.setText(studSearch.getEmail());
           txtAge.setText(String.valueOf(studSearch.getAge()));
           txtGender.setText(studSearch.getGender());
           txtFaculty.setText(studSearch.getFaculty());
           txtDepartment.setText(studSearch.getDepatment());
           txtstudentId.setEditable(false);
           
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,"Error in method"+ e.getMessage());
        }
    }
    private void btnToRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnToRegisterActionPerformed
        // TODO add your handling code here:
        StudentInfo student = new StudentInfo();
        StudentDao studDao= new StudentDao();
        String studentId=txtstudentId.getText().trim();
        String fullName=txtFullName.getText().trim();
        String email=txtEmail.getText().trim();
        int age=Integer.parseInt(txtAge.getText().trim());
        String gender=txtGender.getText().trim();
        String faculty=txtFaculty.getText().trim();
        String department=txtDepartment.getText().trim();
        

        
        try {
            student.setStudent_Id(studentId);
            student.setStudent_name(fullName);
            student.setEmail(email);
            student.setAge(age);
            student.setGender(gender);
            student.setFaculty(faculty);
            student.setDepatment(department);
            int rows=studDao.registerStudent(student);
            if (rows>0) {
                clearFields();
                JOptionPane.showMessageDialog(this," Registration Success Fully");
                loadTable();
            }
            
            
        } catch (Exception e) {
        JOptionPane.showMessageDialog(this,"Database Error"+ e.getMessage());
        }
        
        
        
        
       

        
    }//GEN-LAST:event_btnToRegisterActionPerformed

