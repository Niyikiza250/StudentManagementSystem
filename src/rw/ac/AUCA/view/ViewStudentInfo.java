    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        try {
            
          int Answer = JOptionPane.showConfirmDialog(null, "ARE YOU SURE YOU WANT TO UPDATE");
          
          
          if(Answer== JOptionPane.YES_OPTION){
           
          
              String student_Id=txtstudentId.getText();
              String student_name=txtFullName.getText();
              String email=txtEmail.getText();
              int age=Integer.parseInt(txtAge.getText());
              String gender=txtGender.getText();
              String faculty=txtFaculty.getText();
              String depatment=txtDepartment.getText();
              
              
              StudentInfo studentToUpdate = new StudentInfo( student_Id, student_name, email,  age,gender,  faculty,  depatment);
              

              StudentDao studentdaoUpdate= new StudentDao();
              int rows=studentdaoUpdate.updateStudent(studentToUpdate);
              
              if(rows>0){
                  
                  JOptionPane.showMessageDialog(null, "UPDATED");
                  loadTable();
              }
              
              else{
                  JOptionPane.showMessageDialog(null, "ERROR HERE");
              }
         
              
              
          }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,"DATABASE ERROR" +e.getMessage());
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

